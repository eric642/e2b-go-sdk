// Default request timeout (matches Python/JS SDK).
const (
	DefaultRequestTimeout    = 60 * time.Second
	KeepAlivePingIntervalSec = transport.KeepalivePingIntervalSec
	KeepAlivePingHeader      = transport.HeaderKeepalivePing
	DefaultDomain            = "e2b.app"
	// DefaultRetries is the number of control-plane retries applied when
	// Config.Retries is nil.
	DefaultRetries = transport.DefaultRetries
	envdPort       = transport.EnvdPort
	defaultUser    = "user"
)

// HTTP protocol versions accepted by Config.HTTPVersion.
const (
	HTTPVersion1 = "1.1"
	HTTPVersion2 = "2"
)

// SDKVersion is this SDK's release version. It is kept in lockstep with the
// upstream e2b tag (see spec/E2B_VERSION) and regenerated by
// scripts/sync-spec.sh.
const SDKVersion = version.SDKVersion

// UpstreamTag identifies the E2B git tag whose spec was used to generate
// the REST/Connect-RPC clients in internal/.
const UpstreamTag = version.UpstreamTag

// Config holds connection/auth/transport settings shared by all client calls.
// It mirrors Python's ConnectionConfig and JS's ConnectionOpts.
//
// A zero Config is valid — missing fields fall back to environment variables
// (E2B_API_KEY, E2B_DOMAIN, E2B_ACCESS_TOKEN, E2B_API_URL, E2B_SANDBOX_URL,
// E2B_VOLUME_API_URL, E2B_HTTP_VERSION, E2B_DEBUG) and then to sensible
// defaults.
type Config struct {
	// APIKey authenticates team-scoped requests (X-API-Key header).
	// Defaults to $E2B_API_KEY. When both APIKey and AccessToken are set,
	// only APIKey is sent.
	APIKey string

	// AccessToken authenticates user-scoped requests (Authorization: Bearer).
	// Defaults to $E2B_ACCESS_TOKEN.
	AccessToken string

	// Domain for sandbox URLs and the default API URL. Defaults to $E2B_DOMAIN
	// or "e2b.app".
	Domain string

	// APIURL overrides the control-plane URL. Defaults to https://api.<domain>
	// (or http://localhost:3000 when Debug is true).
	APIURL string

	// SandboxURL overrides the envd URL per-sandbox (testing/tunneling).
	// Defaults to $E2B_SANDBOX_URL.
	SandboxURL string

	// VolumeAPIURL overrides the volume-content API URL. Defaults to
	// $E2B_VOLUME_API_URL, or http://localhost:8080 when Debug is true. When
	// empty the volume package derives https://api.<volume domain> from the
	// domain the control plane returns for each volume.
	VolumeAPIURL string

	// Debug flips the default API URL to localhost and sandbox URLs to http://.
	// Defaults to $E2B_DEBUG == "true".
	Debug bool

	// RequestTimeout bounds a single HTTP request. 0 means "no timeout".
	// When unset (zero Duration) the SDK uses DefaultRequestTimeout; callers
	// can disable it by setting Config.RequestTimeoutDisabled = true.
	RequestTimeout         time.Duration
	RequestTimeoutDisabled bool

	// Retries is the number of control-plane retries for responses marked
	// `Should-Retry: true`, or 429/502/503/504 responses without that header
	// (`Should-Retry: false` is never retried), and for failures to establish
	// the connection. Waits honor Retry-After, otherwise jittered exponential
	// backoff from 100ms to 10s; a retry whose wait would exhaust the request
	// timeout is skipped. nil means DefaultRetries (3); a pointer to 0
	// disables retries; negative values are treated as 0. Retries never apply
	// to envd (data-plane) traffic.
	Retries *int

	// Proxy is an HTTP(S) or SOCKS5 proxy URL used for every SDK request
	// (control plane, envd and volume content); a bare "host:port" means
	// http://host:port. When empty, the standard HTTP_PROXY/HTTPS_PROXY/
	// NO_PROXY environment variables apply. NewClient rejects an unusable
	// value with *InvalidArgumentError, and requests never silently bypass a
	// configured proxy. Ignored when HTTPClient is set.
	Proxy string

	// HTTPVersion selects the HTTP protocol: HTTPVersion1 ("1.1") disables
	// HTTP/2, HTTPVersion2 ("2") enables HTTP/2 over TLS (with HTTP/1.1
	// fallback). Defaults to $E2B_HTTP_VERSION, else Go's default (HTTP/2
	// negotiated over TLS). NewClient rejects any other value with
	// *InvalidArgumentError. Ignored when HTTPClient is set.
	HTTPVersion string

	// Headers added to every control-plane REST request. They are never sent
	// to envd (use ExtraSandboxHeaders for that).
	Headers map[string]string

	// ExtraSandboxHeaders added only to envd traffic. They can never set the
	// envd Authorization header.
	ExtraSandboxHeaders map[string]string

	// HTTPClient optionally overrides the transport. If nil the SDK builds
	// clients on a shared, pooled transport honoring Proxy and HTTPVersion.
	// Control-plane requests wrap its Transport with the retry policy.
	HTTPClient *http.Client
}

func (c Config) resolve() Config {
	out := c.Clone()

	if out.Domain == "" {
		if v := os.Getenv("E2B_DOMAIN"); v != "" {
			out.Domain = v
		} else {
			out.Domain = DefaultDomain
		}
	}
	if out.APIKey == "" {
		out.APIKey = os.Getenv("E2B_API_KEY")
	}
	if out.AccessToken == "" {
		out.AccessToken = os.Getenv("E2B_ACCESS_TOKEN")
	}
	if !out.Debug {
		out.Debug = strings.EqualFold(os.Getenv("E2B_DEBUG"), "true")
	}
	if out.APIURL == "" {
		if v := os.Getenv("E2B_API_URL"); v != "" {
			out.APIURL = v
		} else if out.Debug {
			out.APIURL = "http://localhost:3000"
		} else {
			out.APIURL = "https://api." + out.Domain
		}
	}
	if out.SandboxURL == "" {
		out.SandboxURL = os.Getenv("E2B_SANDBOX_URL")
	}
	if out.VolumeAPIURL == "" {
		if v := os.Getenv("E2B_VOLUME_API_URL"); v != "" {
			out.VolumeAPIURL = v
		} else if out.Debug {
			out.VolumeAPIURL = "http://localhost:8080"
		}
	}
	if out.HTTPVersion == "" {
		out.HTTPVersion = os.Getenv("E2B_HTTP_VERSION")
	}
	if out.RequestTimeout == 0 && !out.RequestTimeoutDisabled {
		out.RequestTimeout = DefaultRequestTimeout
	}
	if out.Headers == nil {
		out.Headers = map[string]string{}
	}
	if _, ok := out.Headers["User-Agent"]; !ok {
		out.Headers["User-Agent"] = userAgent()
	}
	return out
}

func userAgent() string {
	return "e2b-go-sdk/" + SDKVersion + " (" + runtime.GOOS + "/" + runtime.GOARCH + ")"
}

func (c Config) retries() int {
	if c.Retries == nil {
		return DefaultRetries
	}
	return max(*c.Retries, 0)
}

func (c Config) envdHeaders() map[string]string {
	out := make(map[string]string, len(c.ExtraSandboxHeaders)+1)
	ua := userAgent()
	if v, ok := c.Headers["User-Agent"]; ok && v != "" {
		ua = v
	}
	out["User-Agent"] = ua
	maps.Copy(out, c.ExtraSandboxHeaders)
	return out
}

func (c Config) sandboxURL(sandboxID, sandboxDomain string) string {
	if c.SandboxURL != "" {
		return c.SandboxURL
	}
	scheme := "https"
	if c.Debug {
		scheme = "http"
	}
	return scheme + "://" + c.sandboxHost(sandboxID, sandboxDomain, envdPort)
}

func (c Config) sandboxHost(sandboxID, sandboxDomain string, port int) string {
	if c.Debug {
		return "localhost:" + strconv.Itoa(port)
	}
	if sandboxDomain == "" {
		sandboxDomain = c.Domain
	}
	return strconv.Itoa(port) + "-" + sandboxID + "." + sandboxDomain
}

type transportKey struct {
	proxy       string
	httpVersion string
}

var (
	transportsMu sync.Mutex
	transports   = map[transportKey]*http.Transport{}
)

func (c Config) baseTransport() *http.Transport {
	key := transportKey{proxy: c.Proxy, httpVersion: c.HTTPVersion}
	transportsMu.Lock()
	defer transportsMu.Unlock()
	if t, ok := transports[key]; ok {
		return t
	}
	t := newBaseTransport(key)
	transports[key] = t
	return t
}

func newBaseTransport(key transportKey) *http.Transport {
	t := &http.Transport{
		Proxy: http.ProxyFromEnvironment,
		DialContext: (&net.Dialer{
			Timeout:   30 * time.Second,
			KeepAlive: 30 * time.Second,
		}).DialContext,
		ForceAttemptHTTP2:     true,
		MaxIdleConns:          100,
		MaxIdleConnsPerHost:   20,
		IdleConnTimeout:       90 * time.Second,
		TLSHandshakeTimeout:   10 * time.Second,
		ExpectContinueTimeout: 1 * time.Second,
	}
	if key.proxy != "" {
		u, err := parseProxyURL(key.proxy)
		if err != nil {
			t.Proxy = func(*http.Request) (*url.URL, error) { return nil, err }
		} else {
			t.Proxy = http.ProxyURL(u)
		}
	}
	if v, err := normalizeHTTPVersion(key.httpVersion); err == nil {
		switch v {
		case HTTPVersion1:
			var p http.Protocols
			p.SetHTTP1(true)
			t.Protocols = &p
			t.ForceAttemptHTTP2 = false
		case HTTPVersion2:
			var p http.Protocols
			p.SetHTTP1(true)
			p.SetHTTP2(true)
			t.Protocols = &p
		}
	}
	return t
}

func parseProxyURL(raw string) (*url.URL, error) {
	s := strings.TrimSpace(raw)
	if !strings.Contains(s, "://") {
		s = "http://" + s
	}
	u, err := url.Parse(s)
	if err != nil {
		return nil, &InvalidArgumentError{Message: "invalid Proxy " + strconv.Quote(raw) + ": " + err.Error()}
	}
	switch strings.ToLower(u.Scheme) {
	case "http", "https", "socks5", "socks5h":
	default:
		return nil, &InvalidArgumentError{Message: "invalid Proxy " + strconv.Quote(raw) + ": unsupported scheme " + strconv.Quote(u.Scheme)}
	}
	if u.Host == "" {
		return nil, &InvalidArgumentError{Message: "invalid Proxy " + strconv.Quote(raw) + ": missing host"}
	}
	return u, nil
}

func normalizeHTTPVersion(v string) (string, error) {
	switch strings.ToLower(strings.TrimSpace(v)) {
	case "":
		return "", nil
	case "1.1", "1", "http/1.1":
		return HTTPVersion1, nil
	case "2", "2.0", "h2", "http/2":
		return HTTPVersion2, nil
	}
	return "", &InvalidArgumentError{Message: "invalid HTTPVersion " + strconv.Quote(v) + `: want "1.1" or "2"`}
}

func (c Config) validate() error {
	if c.HTTPClient == nil && c.Proxy != "" {
		if _, err := parseProxyURL(c.Proxy); err != nil {
			return err
		}
	}
	if c.HTTPClient == nil {
		if _, err := normalizeHTTPVersion(c.HTTPVersion); err != nil {
			return err
		}
	}
	return nil
}

func (c Config) httpClient() *http.Client {
	if c.HTTPClient != nil {
		return c.HTTPClient
	}
	return &http.Client{Transport: c.baseTransport(), Timeout: c.RequestTimeout}
}

// Clone returns a copy of c with Headers, ExtraSandboxHeaders, and Retries
// deep-copied so mutating the returned Config cannot alias c.
func (c Config) Clone() Config {
	out := c
	out.Headers = maps.Clone(c.Headers)
	out.ExtraSandboxHeaders = maps.Clone(c.ExtraSandboxHeaders)
	if c.Retries != nil {
		r := *c.Retries
		out.Retries = &r
	}
	return out
}

// Validate checks that Proxy and HTTPVersion (when HTTPClient is nil) are
// valid, returning *InvalidArgumentError otherwise.
func (c Config) Validate() error { return c.validate() }

// Resolve returns a Config copy with environment-variable fallbacks and
// defaults applied. Safe to call on a zero Config. The returned Config never
// aliases the caller's Headers / ExtraSandboxHeaders maps.
func (c Config) Resolve() Config { return c.resolve() }

// ResolvedHTTPClient returns the HTTP client this Config would use without
// control-plane retries: the HTTPClient field if set, else an *http.Client on
// the shared pooled transport with RequestTimeout. Named with the Resolved-
// prefix because it would otherwise collide with the HTTPClient struct field.
//
// Call it on a resolved Config (see Resolve).
func (c Config) ResolvedHTTPClient() *http.Client { return c.httpClient() }

// ControlPlaneHTTPClient returns the *http.Client for control-plane REST
// requests (https://api.<domain>): RequestTimeout bounds each call
// (including retries) and the transport applies the Retries policy. When
// HTTPClient is set, its Transport (or http.DefaultTransport) is wrapped and
// its Timeout, Jar and CheckRedirect are preserved.
//
// Call it on a resolved Config (see Resolve).
func (c Config) ControlPlaneHTTPClient() *http.Client {
	if c.HTTPClient != nil {
		hc := *c.HTTPClient
		hc.Transport = transport.NewRetryTransport(c.HTTPClient.Transport, c.retries())
		return &hc
	}
	return &http.Client{
		Transport: transport.NewRetryTransport(c.baseTransport(), c.retries()),
		Timeout:   c.RequestTimeout,
	}
}

// DataPlaneHTTPClient returns the *http.Client for envd and volume-content
// traffic: the shared pooled base transport with no control-plane retry
// wrapper and no client-wide Timeout, so long-lived envd streams (commands,
// PTY, watch) and large uploads/downloads are not cut off. Callers bound
// unary requests with a context deadline (typically RequestTimeout). When
// HTTPClient is set it is returned unchanged.
//
// Call it on a resolved Config (see Resolve).
func (c Config) DataPlaneHTTPClient() *http.Client {
	if c.HTTPClient != nil {
		return c.HTTPClient
	}
	return &http.Client{Transport: c.baseTransport()}
}
